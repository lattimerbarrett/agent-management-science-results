import sympy as s
from pathlib import Path
import json
H,P=s.symbols('H P')
z2,z3,z4,z5=s.symbols('z2 z3 z4 z5')
z=[z2,z3,z4,z5]
D=4
hs=[s.Integer(1),H]
for i in range(2,D+1):hs.append(s.expand(H*hs[-1]-P*hs[-2]))
v=[]
for i in range(D+1):
    num=s.Integer(2) if i==0 else z[i-1]*hs[i]
    v.append(s.expand(num-sum(hs[j]/s.factorial(j+1)*v[i-j] for j in range(1,i+1))))
cv=[s.Integer(1)]
for k in range(1,D+1):
    cv.append(s.expand(sum((-1)**(j-1)*s.factorial(j)*v[j]*cv[k-j] for j in range(1,k+1))/k))
source=s.Poly(cv[3],H,P).coeffs()+s.Poly(cv[4],H,P).coeffs()
target=[z4-z2**3/12,z3-z2**4/12+z2**2/12-s.Rational(1,3),z5-z2**4/48+z2**2/48-s.Rational(1,60),z2**5-5*z2**3+4*z2]
Gsrc=s.groebner(source,z5,z4,z3,z2)
Gtgt=s.groebner(target,z5,z4,z3,z2)
assert all(Gsrc.reduce(p)[1]==0 for p in target)
assert all(Gtgt.reduce(p)[1]==0 for p in source)
assert s.factor(target[-1])==z2*(z2-2)*(z2-1)*(z2+1)*(z2+2)
sols=[]
for zz in [-2,-1,0,1,2]:
    subs={z2:s.Integer(zz),z3:s.Rational(zz**4-zz**2+4,12),z4:s.Rational(zz**3,12),z5:s.Rational(zz**4-zz**2,48)+s.Rational(1,60)}
    assert all(s.expand(p.subs(subs))==0 for p in source)
    c1=s.expand(cv[1].subs(subs)); c2=s.expand(cv[2].subs(subs))
    expected={-2:(-3*H,2*H**2+P),-1:(-2*H,H**2),0:(-H,0),1:(0,0),2:(H,P)}[zz]
    assert s.expand(c1-expected[0])==0 and s.expand(c2-expected[1])==0
    sols.append({'z2':zz,'c1V':str(c1),'c2V':str(c2)})
# Veronese source rank and binary-quadratic support dimension.
n=s.symbols('n',integer=True,positive=True)
M=(n+1)*(n+2)/2
assert s.expand((M-1)-n*(n+3)/2)==0
assert s.expand((2*(n+1)-1)-1-2*n)==0
out={'c3V':str(cv[3]),'c4V':str(cv[4]),'elimination_generators':[str(e) for e in target],'solutions':sols}
Path('workspace').mkdir(exist_ok=True)
Path('workspace/agent2_top_two_checks.json').write_text(json.dumps(out,indent=2))
src=Path(__file__); dst=Path('workspace/agent2_top_two_checks.py')
if src.resolve()!=dst.resolve():dst.write_text(src.read_text())
print(json.dumps(out,indent=2))
proof=r'''# Width-one bundles with top multiplicity two, n>=5

Let E on P^n, n>=5, be uniform of rank r<2n and type (1,1,0^(r-2)). Let I, p, q, h,H have the conventions in agent2_top_one_proof.md. Put P=c2(S*) on G=Gr(2,n+1). Its relative splitting sequence is
0 -> q*V tensor O(h) -> p*E -> q*W -> 0,
where rank V=2. On each alpha-plane A_x=p^{-1}(x)=P^{n-1}, V is a subbundle of O^r, hence V*|A_x is globally generated.

## Numerical determination of V
Write ch(E)=r+2h+z2 h^2+z3 h^3+z4 h^4+z5 h^5+... . For Chern roots x,y of S*, q-relative pushforward gives
ch(V)=(ch(E)(x)-ch(E)(y))/(exp(x)-exp(y)).
This follows directly by applying the projective-bundle pushforward to p*E(-h), whose derived pushforward is V; equivalently use GRR. Expanding the quotient uses h_i(x,y)=sum x^j y^(i-j), generated by h_0=1,h_1=H,h_i=Hh_(i-1)-Ph_(i-2). There are no Grassmannian Chow relations in degrees at most four, since its first relation has degree n>=5.
The equations c3(V)=c4(V)=0 generate precisely the ideal
z4-z2^3/12,
z3-z2^4/12+z2^2/12-1/3,
z5-z2^4/48+z2^2/48-1/60,
z2(z2-2)(z2-1)(z2+1)(z2+2).
Both directions of ideal membership are verified exactly by agent2_top_two_checks.py. Thus the possibilities for (c1(V),c2(V)) are
z2=-2: (-3H,2H^2+P);
z2=-1: (-2H,H^2);
z2= 0: (-H,0);
z2= 1: (0,0);
z2= 2: (H,P).
The last is impossible, since det(V*|A_x)=O(-1) is not globally generated.

## Reconstructing V (no Chern-class uniqueness assumption)
A globally generated rank-two bundle B on P^m, m>=4, with (c1,c2)=(2,1) is O(1)^2; with (c1,c2)=(3,2) it is O(1) plus O(2). Indeed a general section has smooth codimension-two zero locus Z of degree one or two. In dimension m>=4 two components of dimension m-2 intersect by the projective dimension theorem, so Z is connected. A degree-one variety is linear; a degree-two variety spans a hyperplane and is a quadric hypersurface there (the elementary degree>=codimension+1 bound proves this). Thus Z is the complete intersection (1,1) or (1,2). The extension 0->O->B->I_Z(c1)->0 is unique up to scalar among locally free extensions, as follows from the Koszul resolution, so B is O1^2 or O1 plus O2.
For c1=c2=0, global generation makes B trivial; for c1=1,c2=0 a general section has empty zero locus and the extension splits, giving O plus O1.

Consequently the restrictions V|A_x, in the four remaining cases, are respectively O(-1) plus O(-2), O(-1)^2, O plus O(-1), and O^2. These determine V globally using incidence, as follows.
A bundle on G trivial on every alpha-plane is trivial: pull it to I, descend along p to P^n, use that the descended bundle is trivial on every line (q-fibers), then push back along q. Thus the second and fourth possibilities give V=O_G(-1)^2 and V=O_G^2.
In the third case, the alpha-relative top O determines a line O(kh) in q*V with quotient O(-H-kh). Its second Chern class is -k hH-k^2h^2. Since c2(V)=0, independence of hH,h^2 forces k=0. Pushing to G gives V=O plus O(-H), since H^1(G,O(H))=0. This vanishing also follows by pulling to I and using p_*O(H)=Omega^1_Pn(2) and the Euler sequence.
In the first case, apply the same construction to B=V(H). It has c1=-H,c2=P; comparison with -k hH-k^2h^2=P=hH-h^2 forces k=-1. Thus
0->O(-h)->q*B->O(h-H)->0.
Push along q. O(-h) has no q-fiber cohomology, so B=q_*O(h-H)=S* tensor O(-H)=S. Therefore V=S tensor O(-H).

## Elementary source reconstruction
For each obtained V define a homogeneous source B with the same positive relative block q*V tensor O(h):
V=O^2: B=O(1)^2;
V=O plus O(-H): B=O(1) plus Q;
V=O(-H)^2: B=Q^2;
V=S(-H): B=coker[O(-2)->Sym^2 C^{n+1} tensor O], where the map sends x to x^2.
Here Q=T_Pn(-1). In each case p_*(q*V* tensor O(-h))=B*. For the last, the fiber is the vector space of quadrics vanishing at x: restricting such a quadric to each two-plane containing x factors it by the linear coordinate vanishing at x. This identifies it with H^0(A_x,q*S* tensor O(H-h)), and yields B* as kernel[Sym^2(C^{n+1})* tensor O->O(2)].
Dual adjunction of q*V tensor O(h)->p*E therefore gives a canonical morphism B->E which is the identity on the positive relative block.
On each line L this morphism has block matrix with the map on O(1)^2 invertible and the map between the degree-zero pieces constant. Its rank is constant on L; since every two points lie on a line, rank is globally constant. Kernel and cokernel restrict trivially on all lines, hence are trivial bundles. Writing E' for the image, we have
0->O^k->B->E'->0,   0->E'->E->O^c->0.
The latter splits: H^1(E')=0 follows from H^1(B)=H^2(O)=0. These vanishings follow from Euler or the defining Veronese sequence.

For B=O(1)^2 the kernel is zero by rank. For B=O(1) plus Q it is also zero: any nonzero trivial kernel section has Q component represented by a vector v. If v=0 it vanishes somewhere; otherwise on a line containing [v], the section lies entirely in the positive O(1)^2 subbundle, contradicting that B->E is injective on that subbundle. Hence these two cases yield exactly the homogeneous bundles O(1)^2 plus trivial summands and O(1) plus Q plus trivial summands.

For B=Q^2 or the Veronese quotient, pulling O^k back through the defining sequence for B splits the inverse-image extension, since H^1(O(-1))=H^1(O(-2))=0. Cancel the resulting constant trivial summands. This gives respectively
0->O(-1)^2->O^N->E'->0,
0->O(-2)->O^N->E'->0.
Uniform splitting (1,1,0,...) forces both ranks to be at least 2n. In the first case dual uniform restriction means a subspace of (C^2)* tensor (C^{n+1})* surjects onto (C^2)* tensor U* for every two-plane U. Its annihilator contains no rank<=2 tensor; every tensor here has rank<=2, so the annihilator is zero. Therefore N>=2(n+1), rank E'=N-2>=2n.
In the second, the annihilator of the N-dimensional system of quadrics avoids every nonzero quadratic supported on a two-plane, i.e. the symmetric rank<=2 locus. Its projective dimension is 2n. The projective dimension theorem gives N>=2n+1, so rank E'=N-1>=2n. Both contradict rank E<2n.

Conclusion: for n>=5 and r<2n, every uniform type (1,1,0^(r-2)) bundle is O(1)^2 plus trivial bundles, or Q plus O(1) plus trivial bundles. Dual/twist gives the bottom-multiplicity-two version. The numerical ideal computation is exact, finite, and independent of n; all remaining steps are proved geometrically above. This is not a proof of the full problem for min splitting multiplicity>=3 or splitting width>=2.
'''
Path('workspace/agent2_top_two_proof.md').write_text(proof)
