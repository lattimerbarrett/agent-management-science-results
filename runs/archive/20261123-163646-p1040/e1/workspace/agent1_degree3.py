"""Exact exploratory degree-three relation computation for IA3.
Every relation column is justified by an actual exact commuting identity.
PASS only if full primitive Johnson kernel is obtained.
"""
from itertools import product, combinations
from functools import lru_cache
from sage.all import Matrix, ZZ
from degree1_certificate import generators
from degree2_certificate import red, inv, compose

N=3
G=[]
for name,i,w in generators(N):
 f=[(j+1,) for j in range(N)];f[i]=w;G.append(tuple(f))
m=len(G)

def mul(a,b,lim=3):
 out={}
 for u,x in a.items():
  for v,y in b.items():
   if len(u)+len(v)<=lim:out[u+v]=out.get(u+v,0)+x*y
 return {w:x for w,x in out.items() if x}
def add(a,b,k=1):
 out=a.copy()
 for w,x in b.items():out[w]=out.get(w,0)+k*x
 return {w:x for w,x in out.items() if x}
def br(a,b):return add(mul(a,b,20),mul(b,a,20),-1)
def expand(w):
 a={():1}
 for s in w:
  i=abs(s)-1
  f={():1,(i,):1} if s>0 else {tuple([i]*j):(-1)**j for j in range(4)}
  a=mul(a,f)
 return a

def commuting_relators():
 cand=[]
 for i,g in enumerate(G):cand.append((g,(i+1,)))
 for i,j in combinations(range(m),2):
  cand.append((compose(G[i],G[j]),(i+1,j+1)))
  cand.append((compose(G[j],G[i]),(j+1,i+1)))
 seen=set();out=[]
 for (a,u),(b,v) in combinations(cand,2):
  if compose(a,b)!=compose(b,a):continue
  w=red(u+v+inv(u)+inv(v));ex=expand(w)
  if any(len(t)==1 and x for t,x in ex.items()):raise ValueError('bad')
  key=tuple(sorted((t,x) for t,x in ex.items() if 2<=len(t)<=3))
  if not key or key in seen:continue
  seen.add(key);out.append((w,ex))
 return out

def lyndon(w):return bool(w) and all(w < w[j:]+w[:j] for j in range(1,len(w)))
@lru_cache(None)
def lp(w):
 if len(w)==1:return {w:1}
 j=next(j for j in range(1,len(w)) if lyndon(w[j:]))
 return br(lp(w[:j]),lp(w[j:]))
L3=[w for w in product(range(m),repeat=3) if lyndon(w)]
LP=[lp(w) for w in L3]
def coords(p):
 p=p.copy();v=[]
 for w,q in zip(L3,LP):
  x=p.get(w,0);v.append(x)
  if x:p=add(p,q,-x)
 assert not p,('not free Lie',p)
 return v

def deriv(d,p):
 out={}
 for w,x in p.items():
  for j,t in enumerate(w):
   for v,y in d[t].items():out[w[:j]+v+w[j+1:]]=out.get(w[:j]+v+w[j+1:],0)+x*y
 return {w:x for w,x in out.items() if x}
def dbr(d,e):return tuple(add(deriv(d,e[i]),deriv(e,d[i]),-1) for i in range(N))
Ds=[]
for name,i,w in generators(N):
 # Calculate degree-two displacement using the same generic Magnus routine.
 ex=expand(w+(-i-1,));d=[{} for _ in range(N)]
 d[i]={t:x for t,x in ex.items() if len(t)==2};Ds.append(tuple(d))
@lru_cache(None)
def ld(w):
 if len(w)==1:return Ds[w[0]]
 j=next(j for j in range(1,len(w)) if lyndon(w[j:]))
 return dbr(ld(w[:j]),ld(w[j:]))

def main():
 rel=commuting_relators();print('actual commuting relators',len(rel),flush=True)
 pairs=list(combinations(range(m),2))
 R2=Matrix(ZZ,[[ex.get((i,j),0) for w,ex in rel] for i,j in pairs])
 K=R2.right_kernel().basis_matrix();print('R2 rank',R2.rank(),'integer syzygies',K.nrows(),flush=True)
 cols=[]
 for w,ex in rel:
  q={t:x for t,x in ex.items() if len(t)==2}
  for i in range(m):cols.append(coords(br({(i,):1},q)))
 for z in K.rows():
  p={}
  for x,(_,ex) in zip(z,rel):
   if x:p=add(p,{t:y for t,y in ex.items() if len(t)==3},x)
  if p:cols.append(coords(p))
 M=Matrix(ZZ,cols).transpose();print('cubic relation matrix',M.dimensions(),'rank',M.rank(),flush=True)
 keys=[(i,w) for i in range(N) for w in product(range(N),repeat=4)]
 B=Matrix(ZZ,[[ld(w)[i].get(t,0) for w in L3] for i,t in keys])
 print('domain',len(L3),'Johnson rank',B.rank(),'kernel',len(L3)-B.rank(),flush=True)
 assert B*M==0
 H=M.hermite_form(include_zero_rows=False) if False else None
 S=M.smith_form(transformation=False)
 diag=[abs(S[i,i]) for i in range(min(S.dimensions())) if S[i,i]]
 print('SNF counts',{int(x):diag.count(x) for x in set(diag)},flush=True)
 if len(diag)==len(L3)-B.rank() and all(x==1 for x in diag):
  print('PASS: full integral degree3 Johnson kernel generated by verified relations')
 else:print('INCOMPLETE relation lattice; no injectivity claim')
 return B,M,rel
if __name__=='__main__':main()
