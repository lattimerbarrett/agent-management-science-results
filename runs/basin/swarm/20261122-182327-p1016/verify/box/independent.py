import itertools as it
import sympy as s
# Verify that age-one elements generate each of the six groups (needed for Cox facts).
for m,n in [(1,1),(1,2),(1,3),(2,2),(2,3),(3,3)]:
 G={(i,j,e) for i in range(2*m) for j in range(2*n) for e in (0,1) if (i-j)%2==0}
 def mul(x,y):
  i,j,e=x; I,J,E=y
  return ((i+(-1)**e*I)%(2*m),(j+(-1)**e*J)%(2*n),(e+E)%2)
 juniors={g for g in G if (1 if g[2] else (g[0]!=0)+(g[1]!=0))==1}
 closure={(0,0,0)}
 while True:
  new=closure|{mul(x,y) for x in closure for y in juniors}
  if new==closure: break
  closure=new
 assert closure==G
 print((m,n),'generated by juniors')
# Check conjugation for (2,2), including a splitting involution.
i=s.I
k=s.diag(s.Matrix([[0,1],[1,0]]),s.Matrix([[0,1],[1,0]]))
s1=s.diag(-1,-1,1,1); s2=s.diag(1,1,-1,-1)
d=s.diag(i,-i,i,-i)
# columns diagonalize k, and rescale so d*k becomes the double transposition
C=s.diag(s.Matrix([[1,-i],[1,i]]),s.Matrix([[1,-i],[1,i]]))
tau=C.inv()*d*k*C
assert tau==s.diag(s.Matrix([[0,-1],[-1,0]]),s.Matrix([[0,-1],[-1,0]])) or tau==s.diag(s.Matrix([[0,1],[1,0]]),s.Matrix([[0,1],[1,0]]))
print('outside involution in diagonalizing coordinates =',tau)
# Explicit A-boundary valuations on the eigen-cover: order(U0+V0)=1,
# order(U0-V0)=m-1 gives normalized weights 1/m,(m-1)/m.
for m in (2,3):
 assert s.Rational(1,m)+s.Rational(m-1,m)==1
 assert min(1,m-1)==1
 assert 1+(m-1)==m
 print('rotational valuation weights:',s.Rational(1,m),s.Rational(m-1,m))
