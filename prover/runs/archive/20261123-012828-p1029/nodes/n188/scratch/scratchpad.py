import sympy as s
eta,t=s.symbols('eta t', positive=True)
D=s.factor((eta-t)/(1-t))
print('Spectral bound: D(p) >=',D,'for 0<t<eta<=1.')
print('Taking t=eta/2:',s.simplify(D.subs(t,eta/2)))
print('Bessel bound: sum p_n <= (1/t)*1.')
print('\nLogical audit:')
print('Verified nonexhaustion => select x_n with tau(x_n)>=epsilon.')
print('Scale individually: y_n=(eta/tau(x_n))*x_n, 0<eta<=epsilon.')
print('Then sum y_n<=1 and tau(y_n)=eta exactly.')
print('A supremum in the original factor is not ruled out by these bounds.')
print('In a countably saturated quasitracial ultrapower, however, any')
print('purported supremum b gives a finitely satisfiable type:')
print('0<=z<=1, z>=a_n for all n, tau((b-z)_+)>=eta/2.')
print('Finite satisfaction uses z=a_N and b-a_N>=a_(N+1)-a_N.')
print('A realization is an upper bound not above b: contradiction.')
