# All finite-degree checks of the common centralizer in the free associative algebra.
# A polynomial commuting with X and Y has coefficient vectors in this kernel.
import sympy as sp
for d in range(1,8):
    words=list(product((0,1),repeat=d)); ix={w:i for i,w in enumerate(words)}
    rows={}
    for v in (0,1):
        for w in words:
            for out,sgn in ((w+(v,),1),((v,)+w,-1)):
                row=rows.setdefault((v,out),{})
                row[ix[w]]=row.get(ix[w],0)+sgn
    M=sp.MutableSparseMatrix(len(rows),len(words),{})
    for i,row in enumerate(rows.values()):
        for j,a in row.items():M[i,j]=a
    rank=M.rank()
    assert rank==2**d
    print('degree',d,': common centralizer kernel dimension',2**d-rank)

