from itertools import product
from collections import defaultdict

def red(w):
    s=[]
    for a in w:
        if s and s[-1]==-a:s.pop()
        else:s.append(a)
    return tuple(s)
def inv(w):return tuple(-x for x in reversed(w))
def app(f,w):
    return red(sum((f[x-1] if x>0 else inv(f[-x-1]) for x in w),()))
def mul(f,g):return tuple(app(f,w) for w in g)
def pw(f,n):
    z=((1,),(2,))
    for _ in range(n): z=mul(z,f)
    return z
