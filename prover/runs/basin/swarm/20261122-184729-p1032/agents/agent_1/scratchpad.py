from itertools import combinations
from collections import Counter, defaultdict
import numpy as np
import sympy as S
from scipy.spatial import ConvexHull

names = 'abcdefghzw'
words = ('bdfhz adfhz acfhz acehz acegz bcegz bdegz bdfgz '
         'bdehw bcfhw bcfgw bcehw adfgw adehw adegw acfgw').split()
G = [tuple(int(x in word) for x in names) for word in words]
one = (1,)*10

def add(u,v): return tuple(a+b for a,b in zip(u,v))
def le(u,v): return all(a<=b for a,b in zip(u,v))
powers = [{(0,)*10}]
for k in range(1,5):
    powers.append({add(u,g) for u in powers[-1] for g in G})
def member(u,k): return any(le(v,u) for v in powers[k])

# Exhaustively enumerate minimal vertex covers.
covers=[]
for r in range(1,11):
    for t in combinations(range(10),r):
        t=frozenset(t)
        if all(any(g[i] for i in t) for g in G) and not any(c<=t for c in covers):
            covers.append(t)
coverwords=[''.join(names[i] for i in sorted(c)) for c in covers]
expected=('ab cd ef gh zw acez achz adew adgw afgw afhz bcfw bchw '
          'bdfz bdgz begz behw cegz cfgw dehw dfhz').split()
assert set(coverwords)==set(expected)
print('Minimal covers:', ', '.join(coverwords))

# The cone inequalities are x_i >= 0, t >= 0, and sum_C x_i >= t.
B=S.Matrix([[int(i==j) for i in range(11)] for j in range(11)] +
           [[int(i in c) for i in range(10)]+[-1] for c in covers])
R=S.Matrix([[int(i==j) for i in range(10)]+[0] for j in range(10)] +
           [list(g)+[1] for g in G])
assert all(x>=0 for x in B*R.T)
assert all(x>=0 for x in B*S.Matrix([1]*10+[2]))

# Floating point only proposes a list of simplices. Everything used below
# about that list is independently checked over the rationals.
rr=np.array(R.tolist(), dtype=np.int64)
lengths=rr[:,:10].sum(axis=1)
points=rr[:,list(range(9))+[10]]/lengths[:,None]
heights=np.random.default_rng(2026).integers(1,10**9,size=26)
hull=ConvexHull(np.column_stack([points,heights/10**9]))
proposed={tuple(sorted(s)) for s,eq in zip(hull.simplices,hull.equations)
          if eq[-2]<-1e-8}
simplices=[]
inverses={}
dets=Counter()
weights=S.Matrix([int(heights[i])*int(lengths[i]) for i in range(26)])
for s in sorted(proposed):
    A=R[list(s),:]
    determinant=A.det()
    if determinant==0: continue
    inv=A.inv()
    support=inv*weights[list(s),:]
    slack=weights-R*support
    assert all(slack[i]==0 if i in s else slack[i]>0 for i in range(26))
    simplices.append(s)
    inverses[s]=inv
    dets[abs(int(determinant))]+=1
assert simplices

# Exact boundary certificate: internal facets are paired; each unpaired
# facet lies on the boundary of the stated cone.
faces=defaultdict(list)
for s in simplices:
    for j in s:
        faces[tuple(i for i in s if i!=j)].append(j)
for f,opposite in faces.items():
    assert len(opposite) in (1,2)
    if len(opposite)==1:
        vals=B*R[list(f),:].T
        assert any(all(vals[i,j]==0 for j in range(10)) for i in range(B.rows))
    else:
        # Opposite vertices really are on opposite sides of their facet.
        n=R[list(f),:].nullspace()[0]
        assert (R[opposite[0],:]*n)[0]*(R[opposite[1],:]*n)[0]<0
print('Cone simplices:',len(simplices),'determinants:',dict(sorted(dets.items())))
print('Facet incidences:',dict(sorted(Counter(map(len,faces.values())).items())))

# Enumerate all lattice points in each fundamental parallelepiped.
remainders={(0,)*11}
for s in simplices:
    A=R[list(s),:]
    inv=inverses[s]
    d=abs(int(A.det()))
    adj=inv*d
    assert all(x.q==1 for x in adj)
    residue_generators=[tuple(map(int,row)) for row in adj.tolist()]
    residues={(0,)*11}
    todo=list(residues)
    while todo:
        u=todo.pop()
        for row in residue_generators:
            v=tuple((a+b)%d for a,b in zip(u,row))
            if v not in residues:
                residues.add(v);todo.append(v)
    assert len(residues)==d
    for r in residues:
        v=S.Matrix([r])*A/d
        assert all(x.q==1 for x in v)
        remainders.add(tuple(map(int,v)))
for v in remainders:
    u,k=v[:10],v[10]
    # Membership in the monoid generated by R's rows and (1,...,1,2).
    assert any(member(tuple(a-q for a in u),k-2*q) for q in range(k//2+1))
print('Parallelepiped points:',len(remainders),
      'degrees:',dict(sorted(Counter(v[-1] for v in remainders).items())))

# All exceptional symbolic-generator reduction identities.
assert not member(one,2)
assert all(member(add(one,tuple(int(i==j) for i in range(10))),2) for j in range(10))
assert all(member(add(one,g),3) for g in G)
assert member((2,)*10,4)
print('Checked: M not in I^2; x_i M in I^2; M I in I^3; M^2 in I^4.')
print('All certificates verified.')

