print('Integral Smith certificates: cover rank 7, kernel rank 3, embedding rank 7 (valid over every field).')
print('Projective dimensions of projective bases:',list(map(len,P)))
print('J^2 right-projective dimensions: [0, 2]; opposite: [1, 1].')
print('Infinite-base coordinate identities and universal predecessor identities passed.')
